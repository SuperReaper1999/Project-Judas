// Sprout Patch: a small top-down farming slice. Native MK2 owns the player's
// planar motion/collision; the tilemap owns soil/crop presentation. This script
// owns the farming rules, touch/keyboard controls, HUD, camera and save policy.
import {input,saves,scenes,ui,world} from 'judas';

export const properties={
  grid:{type:'entity',default:null}, cursor:{type:'entity',default:null},
  speed:{type:'number',default:4}, acceleration:{type:'number',default:35},
  growSeconds:{type:'number',default:6}, canCapacity:{type:'number',default:5},
  startSeeds:{type:'number',default:6}, goal:{type:'number',default:3},
  fieldMinX:{type:'number',default:-3}, fieldMinY:{type:'number',default:-4},
  fieldMaxX:{type:'number',default:4}, fieldMaxY:{type:'number',default:0},
  pondMinX:{type:'number',default:-9}, pondMinY:{type:'number',default:1},
  pondMaxX:{type:'number',default:-7}, pondMaxY:{type:'number',default:4}
};

// Tile sheet frames (cell-<row>-<col>), generated by tools/demos/sprout_patch/make_art.py.
const DRY='cell-1-1', WET='cell-1-2', STAGES=['cell-1-3','cell-2-0','cell-2-1','cell-2-2'];
const RIPE=STAGES.length-1, TILLED=-1;
const TOOLS=['hoe','seeds','water'];
const BUTTONS={'btn-hoe':'hoe','btn-seeds':'seeds','btn-water':'water','btn-use':'use','btn-save':'save','btn-load':'load'};
const STICK_RADIUS=.11; // fraction of screen height
const HUD='farm_hud';

export default class SproutPatch {
  /** @param {import('judas').ScriptContext} context */
  constructor({entity,properties}){
    this.entity=entity;this.properties=properties;
    this.state={tool:'hoe',seeds:properties.startSeeds,water:0,harvested:0,won:false,
      plots:{},facing:{x:0,y:-1},time:0,uses:0,request:null,
      message:'Till the soil inside the fence, plant, water, wait, harvest!'};
    // Presentation/input helpers only; never saved.
    this.doc=null;this.reference=null;this.seen=new Set();this.stick=null;
    this.pending=[];this.lastTouch=-1;this.tint='';this.highlight='';
  }
  start(){this.attachHud();}
  restore(){this.attachHud();}
  attachHud(){this.doc=ui.get(HUD);this.reference=null;this.highlight='';}

  // ---- Farming rules -------------------------------------------------------
  key(x,y){return x+','+y;}
  inside(x,y,p){return x>=this.properties[p+'MinX']&&x<=this.properties[p+'MaxX']&&y>=this.properties[p+'MinY']&&y<=this.properties[p+'MaxY'];}
  /** Cell in front of the player's feet, in tilemap cell coordinates (1 m cells, root at origin). */
  target(position){
    const f=this.state.facing;
    return {x:Math.floor(position.x+f.x*.8),y:Math.floor(position.y-.45+f.y*.8)};
  }
  /** What USE would do on a cell, without changing anything. */
  describe(x,y){
    const s=this.state,plot=s.plots[this.key(x,y)];
    if(plot&&plot.stage===RIPE)return {ok:true,hint:'USE: harvest the ripe turnip'};
    if(s.tool==='water'&&this.inside(x,y,'pond'))return {ok:s.water<this.properties.canCapacity,hint:s.water<this.properties.canCapacity?'USE: fill the watering can':'The can is already full'};
    if(!this.inside(x,y,'field'))return {ok:false,hint:s.tool==='water'?'Water the field, or fill the can at the pond':'Face the soil inside the fence'};
    if(s.tool==='hoe')return plot?{ok:false,hint:'Already tilled'}:{ok:true,hint:'USE: till the soil'};
    if(s.tool==='seeds'){
      if(!plot)return {ok:false,hint:'Till this soil with the hoe first'};
      if(plot.stage!==TILLED)return {ok:false,hint:'Something is already growing here'};
      return s.seeds>0?{ok:true,hint:'USE: plant a turnip seed'}:{ok:false,hint:'No seeds left: harvest for more'};
    }
    if(!plot)return {ok:false,hint:'Nothing to water here'};
    if(plot.wet)return {ok:false,hint:'Already watered: wait for it to grow'};
    return s.water>0?{ok:true,hint:'USE: water the soil'}:{ok:false,hint:'The can is empty: fill it at the pond'};
  }
  tile(layer,x,y,frame){
    const grid=this.properties.grid;
    if(!grid?.valid)throw new Error('Sprout Patch needs its farm grid entity');
    if(!grid.setTile(layer,x,y,frame))throw new Error('Tile edit rejected: '+layer+' '+x+','+y);
  }
  use(){
    const s=this.state,cell=this.target(this.entity.transform.position),{x,y}=cell,k=this.key(x,y);
    const plot=s.plots[k],info=this.describe(x,y);
    s.uses++;
    if(!info.ok){s.message=info.hint;return;}
    if(plot&&plot.stage===RIPE){
      this.tile('crops',x,y,null);this.tile('soil',x,y,DRY);
      s.plots[k]={stage:TILLED,wet:false,grow:0};s.harvested++;s.seeds+=1;
      s.message='Harvested a turnip! (+1 seed)';
      if(s.harvested>=this.properties.goal&&!s.won){s.won=true;s.message='Harvest festival! You grew '+s.harvested+' turnips.';}
      return;
    }
    if(s.tool==='water'&&this.inside(x,y,'pond')){s.water=this.properties.canCapacity;s.message='Watering can filled.';return;}
    if(s.tool==='hoe'){this.tile('soil',x,y,DRY);s.plots[k]={stage:TILLED,wet:false,grow:0};s.message='Soil tilled. Plant a seed!';return;}
    if(s.tool==='seeds'){this.tile('crops',x,y,STAGES[0]);plot.stage=0;plot.grow=0;s.seeds--;s.message=plot.wet?'Seed planted in wet soil. Wait for it to grow.':'Seed planted. Now water it!';return;}
    this.tile('soil',x,y,WET);plot.wet=true;s.water--;
    s.message=plot.stage===TILLED?'Soil watered. Plant a seed here.':'Watered! It grows while the soil stays wet.';
  }
  grow(dt){
    const s=this.state;
    for(const [k,plot] of Object.entries(s.plots)){
      if(plot.stage<0||plot.stage>=RIPE||!plot.wet)continue;
      plot.grow+=dt;
      if(plot.grow<this.properties.growSeconds)continue;
      const [x,y]=k.split(',').map(Number);
      plot.stage++;plot.grow=0;plot.wet=false;
      this.tile('crops',x,y,STAGES[plot.stage]);this.tile('soil',x,y,DRY);
      s.message=plot.stage===RIPE?'A turnip is ripe! Face it and press USE.':'Your crop grew, and the soil dried. Water it again.';
    }
  }

  // ---- Simulation ----------------------------------------------------------
  fixedUpdate(dt){
    const s=this.state;s.time+=dt;
    for(const [action,tool] of [['tool_hoe','hoe'],['tool_seeds','seeds'],['tool_water','water']])if(input.pressed(action))this.pending.push(tool);
    if(input.pressed('use'))this.pending.push('use');
    for(const action of this.pending.splice(0)){
      if(TOOLS.includes(action)){s.tool=action;s.message='Selected '+(action==='water'?'watering can':action)+'.';}
      else if(action==='use'){this.use();this.entity.setSpriteAnimation({clip:'interact',time:0,playing:true,loop:false});}
      else if(action==='save'||action==='load')this.saveRequest=action;
    }
    this.grow(dt);
    // Same force-limited top-down policy as the native 2D starter.
    const kx=input.axis('move_x'),ky=input.axis('move_y'),stick=this.stick?.vector??{x:0,y:0};
    let mx=kx+stick.x,my=ky+stick.y;const length=Math.max(1,Math.hypot(mx,my));mx/=length;my/=length;
    if(Math.hypot(mx,my)>.3)s.facing=Math.abs(mx)>Math.abs(my)?{x:Math.sign(mx),y:0}:{x:0,y:Math.sign(my)};
    const v=this.entity.velocity,speed=this.properties.speed;
    let cx=mx*speed-v.x,cy=my*speed-v.y;const change=Math.hypot(cx,cy),limit=this.properties.acceleration*dt;
    if(change>limit){cx*=limit/change;cy*=limit/change;}
    const mass=this.entity.mass;this.entity.applyForce({x:cx*mass/dt,y:cy*mass/dt,z:0});
    if(mx)this.entity.setSprite({flipX:mx<0});
    const a=this.entity.spriteAnimation;
    if(a?.ready&&!(a.clip==='interact'&&!a.finished)){
      const clip=Math.hypot(mx,my)>.05?'run':'idle';
      if(a.clip!==clip||!a.playing)this.entity.setSpriteAnimation({clip,time:0,playing:true,loop:true});
    }
  }

  // ---- Touch / mouse controls (gathered every frame, applied in fixedUpdate) ----
  rect(id){
    const l=this.doc.get(id).layout,r=this.reference;
    const w=(l.anchorMax.x-l.anchorMin.x+l.relativeSize.x)*r.x+l.size.x,h=(l.anchorMax.y-l.anchorMin.y+l.relativeSize.y)*r.y+l.size.y;
    const x=l.anchorMin.x*r.x+l.offset.x-l.align.x*w,y=l.anchorMin.y*r.y+l.offset.y-l.align.y*h;
    return {x:x/r.x,y:y/r.y,w:w/r.x,h:h/r.y};
  }
  buttonAt(x,y){
    for(const [id,action] of Object.entries(BUTTONS)){const r=this.rect(id);if(x>=r.x&&x<=r.x+r.w&&y>=r.y&&y<=r.y+r.h)return action;}
    return null;
  }
  update(){
    if(!this.doc)return;
    const view=world.viewport;if(!view.width||!view.height)return;
    const aspect=view.width/view.height;
    // Make the canvas exactly fill the window so anchors are window fractions.
    // The shorter screen side is 720 units, so controls keep their size in portrait.
    if(!this.reference||Math.abs(this.reference.x/this.reference.y-aspect)>1e-4){
      this.reference=aspect>=1?{x:720*aspect,y:720}:{x:720,y:720/aspect};this.doc.referenceSize=this.reference;
    }
    const touches=input.touches,now=this.state.time,live=new Set();
    if(touches.length)this.lastTouch=now;
    for(const t of touches){
      live.add(t.id);
      if(this.seen.has(t.id))continue;
      this.seen.add(t.id);
      const action=this.buttonAt(t.x,t.y);
      if(action)this.pending.push(action);
      else if(!this.stick&&t.x<.5)this.stick={id:t.id,ox:t.x,oy:t.y,vector:{x:0,y:0}};
    }
    for(const id of [...this.seen])if(!live.has(id))this.seen.delete(id);
    if(this.stick&&!live.has(this.stick.id))this.stick=null;
    if(this.stick){
      const t=touches.find(c=>c.id===this.stick.id);
      let dx=(t.x-this.stick.ox)*aspect/STICK_RADIUS,dy=-(t.y-this.stick.oy)/STICK_RADIUS;
      const m=Math.hypot(dx,dy);if(m>1){dx/=m;dy/=m;}
      this.stick.vector=m<.15?{x:0,y:0}:{x:dx,y:dy};
    }
    // Desktop mouse clicks use the same on-screen buttons; ignore synthesized clicks from recent touches.
    if(input.pressed('tap')&&now-this.lastTouch>.5){const p=input.pointer,action=this.buttonAt(p.x,p.y);if(action)this.pending.push(action);}
  }

  // ---- HUD, camera, save policy -------------------------------------------
  uiUpdate(){
    const s=this.state;
    if(!saves.busy){
      if(input.pressed('restart'))scenes.reload();
      else if(input.pressed('save_game')||this.saveRequest==='save')s.request=saves.save('sprout-patch',{name:'Sprout Patch farm'});
      else if(input.pressed('load_game')||this.saveRequest==='load'){if(saves.exists('sprout-patch'))s.request=saves.load('sprout-patch');else s.message='No saved farm yet. Tap SAVE first.';}
    }
    this.saveRequest=null;
    if(!this.doc)return;
    const request=s.request?saves.status(s.request):null;
    this.doc.get('status').text='Seeds '+s.seeds+'   Water '+s.water+'/'+this.properties.canCapacity+'   Turnips '+s.harvested+'/'+this.properties.goal+(s.won?'   FESTIVAL!':'');
    const cell=this.target(this.entity.transform.position),info=this.describe(cell.x,cell.y);
    this.doc.get('message').text=s.message+'\n'+info.hint+(request&&request.state!=='completed'?'\nSave: '+request.state+(request.error?' - '+request.error:''):'');
    if(this.highlight!==s.tool){
      for(const [id,tool] of [['btn-hoe','hoe'],['btn-seeds','seeds'],['btn-water','water']])
        this.doc.get(id).configure({background:tool===s.tool?{r:.95,g:.72,b:.25,a:.95}:{r:.12,g:.24,b:.16,a:.85}});
      this.highlight=s.tool;
    }
    // The joystick ring follows the controlling finger; it rests bottom-left otherwise.
    if(this.reference){
      const r=this.reference,st=this.stick,base=this.doc.get('joy-base'),knob=this.doc.get('joy-knob');
      const bx=st?st.ox*r.x:150,by=st?st.oy*r.y:r.y-150,kx=bx+(st?st.vector.x:0)*STICK_RADIUS*r.y,ky=by-(st?st.vector.y:0)*STICK_RADIUS*r.y;
      base.setLayout({anchorMin:{x:0,y:0},anchorMax:{x:0,y:0},offset:{x:bx,y:by}});
      knob.setLayout({anchorMin:{x:0,y:0},anchorMax:{x:0,y:0},offset:{x:kx,y:ky}});
    }
  }
  presentationUpdate(){
    const pose=this.entity.presentedTransform,view=world.viewport,aspect=view.width&&view.height?view.width/view.height:16/9;
    // Landscape shows 9 m vertically; portrait shows 9 m across.
    world.setView({position:{x:pose.position.x,y:pose.position.y,z:15},rotation:{x:0,y:0,z:0,w:1}},60,
      {projection:'orthographic',height:aspect>=1?9:9/aspect,near:.01,far:100});
    const cursor=this.properties.cursor;if(!cursor?.valid)return;
    const cell=this.target(pose.position),ok=this.describe(cell.x,cell.y).ok,tint=ok?'ok':'no';
    cursor.transform={position:{x:cell.x+.5,y:cell.y+.5,z:0}};
    if(tint!==this.tint){cursor.setSprite({tint:ok?{x:.7,y:1,z:.6,w:1}:{x:1,y:.45,z:.4,w:.7}});this.tint=tint;}
  }
  destroy(){world.clearView();}
}
